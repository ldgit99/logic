function enqueue(item) {
  const queue = loadQueue();
  queue.push(item);
  saveQueue(queue);
}

function loadQueue() {
  try {
    return JSON.parse(localStorage.getItem(QUEUE_KEY) || '[]');
  } catch {
    return [];
  }
}

function saveQueue(queue) {
  try {
    localStorage.setItem(QUEUE_KEY, JSON.stringify(queue.slice(-200))); // 筌ㅼ뮆? 200揶?
  } catch {
    // localStorage ??몄쎗 ?λ뜃?????얜똻??
  }
}

